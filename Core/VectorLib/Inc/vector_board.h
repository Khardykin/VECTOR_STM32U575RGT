/**
  ******************************************************************************
  * @file    vector_board.h
  * @brief   Бортовая инициализация ДО старта RTOS: один вызов из main()
  *
  *          Смысл модуля - оставить сгенерированные кубом файлы пустыми. В
  *          main.c (USER CODE BEGIN 2) остаётся ровно одна строка:
  *
  *              vector_board_init();
  *
  *          Что она делает по порядку:
  *            0) (VECTOR_DBG_FREEZE_TICK) замораживает тайм-базу HAL (TIM6)
  *               на время остановки ядра отладчиком;
  *            1) поднимает SD_MODE (PC9) - иначе оконечный усилитель в
  *               shutdown и звука не будет вообще; держит ~5 мс на пробуждение;
  *               СТРАХОВКА: как только в CubeMX для PC9 будет выставлен
  *               "GPIO output level = High", шаг можно убрать
  *               (см. docs/SYSTEM.md, раздел 9);
  *            2) sf_probe() - проба внешней SPI flash, JEDEC ID в лог;
  *            3) audio_selftest() x VECTOR_AUDIO_SELFTEST - писк напрямую из
  *               внутренней flash, без очередей/потока/состояний: проверка
  *               всего выходного тракта.
  *
  *          Периферию (SAI, SPI, DMA, таймеры, UART) настраивает ИСКЛЮЧИТЕЛЬНО
  *          CubeMX - этот модуль ничего из неё не конфигурирует.
  *
  *          КОНТЕКСТ: main(), до MX_ThreadX_Init(). Спать и блокироваться
  *          нельзя, поэтому все задержки - ограниченные циклы.
  ******************************************************************************
  */
