#endif

/* Периодический отчёт о системном времени, секунд (0 = не печатать).
   Печатает vector_sys_tick_report() из потока (вызов в lvgl_thread_entry),
   интервал отсчитывается по тику RTOS - по HAL-тику он бы не наступил никогда,
   если тики HAL теряются. Две строки:
     tick 10 s: tx=+1000 hal=+10000 cb=+10000 psc=159 arr=999 keys=+0
     irq load: edges=+0 rx4=+12 rx2=+0 rearm4=+0
   tx - тики ThreadX (SysTick, 100 Гц); hal - насколько вырос HAL_GetTick();
   cb  - сколько раз вызван колбэк тайм-базы. hal и cb должны быть в 10 раз
   больше tx. Вторая строка - детектор шквала прерываний, из-за которого
   тайм-база (приоритет 15) голодает.                                        */
#ifndef VECTOR_LOG_TICK_REPORT_S
#define VECTOR_LOG_TICK_REPORT_S  10u
#endif

#endif /* VECTOR_CONFIG_H */
