/**
  ******************************************************************************
  * @file    vector_tick.h
  * @brief   Время в проекте: ТОЛЬКО тик RTOS (ThreadX), HAL-таймеров тут нет
  *
  *          Решение принято сознательно: HAL_GetTick() зависит от прерывания
  *          тайм-базы TIM6 с приоритетом 15 (ниже всех в проекте), поэтому оно
  *          регулярно теряется - в логе от 11:19 за 10 реальных секунд
  *          приходило 148 прерываний вместо 10000, то есть все таймауты,
  *          антидребезг и паузы растягивались в десятки раз. Тик ThreadX
  *          (SysTick, приоритет 4) в том же замере отставал только из-за
  *          остановок ядра отладчиком.
  *
  *          Разрешение: TX_TIMER_TICKS_PER_SECOND = 100, то есть 10 мс.
  *          Для наших задач хватает: антидребезг 50 мс, пауза цикла 500 мс,
  *          таймауты SPI 250-500 мс.
  *
  *          ВАЖНО ПРО ДО ПЛАНИРОВЩИКА: tx_time_get() до tx_kernel_enter()
  *          всегда 0, а tx_thread_sleep() вызывать нельзя. Поэтому весь код,
  *          работающий до RTOS (sf_probe, ext_init, audio_init, selftest),
  *          таймауты считает НЕ временем, а ограниченным числом проходов цикла
  *          (см. wait_busy() в spiflash.c и guard в audio_selftest()).
  *
  *          Чего в проекте больше нет: HAL_Delay() и HAL_GetTick() в модулях
  *          VectorLib. Внутри HAL-драйверов (HAL_SPI_Transmit(..., timeout))
  *          HAL_GetTick остаётся - это их внутренняя реализация, убрать её
  *          нельзя, не отказываясь от HAL.
  ******************************************************************************
  */
#ifndef VECTOR_TICK_H
#define VECTOR_TICK_H

#include <stdint.h>
#include "tx_api.h"

/* Цена одного тика RTOS в миллисекундах (100 Гц -> 10 мс). */
#define VTICK_RESOLUTION_MS   (1000u / TX_TIMER_TICKS_PER_SECOND)

/* Текущее время в мс. КОНТЕКСТ: любой, включая ISR (чтение одной переменной).
   До старта планировщика всегда 0.                                          */
#define VTICK_MS()            ((uint32_t)(tx_time_get() * VTICK_RESOLUTION_MS))

/* Сколько мс прошло с момента t0 (беззнаковое вычитание корректно и при
   переполнении счётчика тиков - на 100 Гц это ~1.36 года).                   */
#define VTICK_ELAPSED_MS(t0)  ((uint32_t)(VTICK_MS() - (t0)))

/* мс -> тики RTOS, округление вверх (0 мс дают 0 тиков = "не ждать"). */
#define VTICK_MS2TICKS(ms)    ((ULONG)((((uint32_t)(ms)) + VTICK_RESOLUTION_MS - 1u) \
                                        / VTICK_RESOLUTION_MS))

/* Сон ПОТОКА: CPU не грузит, другие потоки работают. Только после старта
   планировщика.                                                              */
#define VTICK_SLEEP_MS(ms)    ((void)tx_thread_sleep(VTICK_MS2TICKS(ms)))

/* Мы сейчас в контексте потока (а не в ISR и не до планировщика)?
   Только в потоке допустимы сон, мьютексы и семафоры.                        */
#define VTICK_IN_THREAD()     (tx_thread_identify() != (TX_THREAD *)0)

#endif /* VECTOR_TICK_H */
